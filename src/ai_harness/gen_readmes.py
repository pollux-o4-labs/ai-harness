# 않는다 — 이쪽은 전체 텍스트를 오프셋으로 훑고 저쪽은 줄 단위로 보아
# 매칭 단위가 다르다. 공유되는 것은 처방이지 코드가 아니다.
_MARK_START_RE = re.compile(r"^[ \t]*" + re.escape(MARK_START), re.MULTILINE)
_MARK_END_RE = re.compile(r"^[ \t]*" + re.escape(MARK_END), re.MULTILINE)

_HEAD_LINES = 25  # 각 파일의 앞부분에서만 BLUF를 찾는다.

# BLUF 추출 패턴(명시적 마커만 — 오탐 방지 위해 느슨한 'BLUF:' 평문 매칭은 두지 않는다).
#   · Markdown : `> **BLUF:** …` / `<!-- BLUF: … -->`
#   · 주석형   : `# BLUF: …` / `// BLUF: …`
#   · JSON     : `"_bluf": "…"`
_BLUF_PATTERNS = [
    re.compile(r"<!--\s*BLUF:\s*(.+?)\s*-->", re.IGNORECASE),
    re.compile(r"^\s*>?\s*\*\*BLUF:\*\*\s*(.+?)\s*$", re.IGNORECASE),
    re.compile(r'"_bluf"\s*:\s*"(.+?)"', re.IGNORECASE),
    re.compile(r"^\s*(?://|#)\s*BLUF:\s*(.+?)\s*$", re.IGNORECASE),
]

TODO_PREFIX = "TODO"  # 폴더 목적 BLUF가 아직 없을 때 표시.

