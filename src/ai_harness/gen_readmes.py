MARK_START = "<!-- BLUF-INDEX:START — auto-generated by ai-harness gen-readmes; 이 블록은 수기 편집 금지 -->"
MARK_END = "<!-- BLUF-INDEX:END -->"

# **줄 시작 앵커가 핵심이다** — 문장 중간 인용은 줄을 시작하지 않으므로 이
# 앵커에 안 걸린다. 이 처방의 근거·실사고 상세는 check_doc_form.py의
